// 個人情報らしい文字（メールアドレス・電話番号・郵便番号）を伏せ字にします。
// AIに送る前に、ブラウザ側とサーバー側の両方でこの処理をかけます。
export function redactPatterns(text: string): string {
  return text
    .replace(/[\w.+-]+@[\w-]+(\.[\w-]+)+/g, "［メールアドレス］")
    .replace(/〒?\s?\d{3}[-－ー]\d{4}(?!\d)/g, "［郵便番号］")
    .replace(/(?<!\d)0\d{1,4}[-－ー(（]?\d{1,4}[-－ー)）]?\d{3,4}(?!\d)/g, "［電話番号］");
}
